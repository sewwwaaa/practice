// Builds src/components/countryAnchors.js from public/world-map.svg.
//
// For every country (ISO 3166-1 alpha-2 id in the SVG) we take its largest
// polygon (the main landmass, so Alaska/Hawaii or overseas territories don't
// drag the point into the ocean) and compute that polygon's area centroid.
// The result is an [x, y] anchor in the SVG's own coordinate space, which the
// Breach Map uses to place live incidents precisely without guessing the
// map projection.
//
// Usage: node scripts/build-country-anchors.js

import fs from 'fs';

const SVG_PATH = 'public/world-map.svg';
const OUT_PATH = 'src/components/countryAnchors.js';

const svg = fs.readFileSync(SVG_PATH, 'utf8');

/** Parse a path made of M/L/l/H/h/V/v/Z commands into polygons. */
function parsePolygons(d) {
  const polygons = [];
  let current = null;
  let x = 0;
  let y = 0;
  let startX = 0;
  let startY = 0;

  const segments = d.match(/[MmLlHhVvZz][^MmLlHhVvZz]*/g) || [];
  for (const seg of segments) {
    const cmd = seg[0];
    const nums = (seg.slice(1).match(/-?\d*\.?\d+(?:e[-+]?\d+)?/gi) || []).map(Number);

    switch (cmd) {
      case 'M':
      case 'm':
        for (let i = 0; i < nums.length; i += 2) {
          if (cmd === 'm') { x += nums[i]; y += nums[i + 1]; } else { x = nums[i]; y = nums[i + 1]; }
          if (i === 0) {
            current = [];
            polygons.push(current);
            startX = x; startY = y;
          }
          current.push([x, y]);
        }
        break;
      case 'L':
        for (let i = 0; i < nums.length; i += 2) { x = nums[i]; y = nums[i + 1]; current.push([x, y]); }
        break;
      case 'l':
        for (let i = 0; i < nums.length; i += 2) { x += nums[i]; y += nums[i + 1]; current.push([x, y]); }
        break;
      case 'H': for (const n of nums) { x = n; current.push([x, y]); } break;
      case 'h': for (const n of nums) { x += n; current.push([x, y]); } break;
      case 'V': for (const n of nums) { y = n; current.push([x, y]); } break;
      case 'v': for (const n of nums) { y += n; current.push([x, y]); } break;
      case 'Z':
      case 'z':
        x = startX; y = startY;
        break;
      default:
        throw new Error(`Unsupported path command "${cmd}"`);
    }
  }
  return polygons.filter(p => p.length >= 3);
}

/** Signed-area centroid of a simple polygon (shoelace formula). */
function polygonCentroid(points) {
  let area = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < points.length; i++) {
    const [x0, y0] = points[i];
    const [x1, y1] = points[(i + 1) % points.length];
    const cross = x0 * y1 - x1 * y0;
    area += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  area /= 2;
  if (Math.abs(area) < 1e-9) {
    const avg = points.reduce((a, [px, py]) => [a[0] + px, a[1] + py], [0, 0]);
    return { area: 0, x: avg[0] / points.length, y: avg[1] / points.length };
  }
  return { area: Math.abs(area), x: cx / (6 * area), y: cy / (6 * area) };
}

// Walk the SVG: <path id="xx" d="..."/> or <g id="xx"> ...<path d="..."/>... </g>
const countryPaths = new Map();
const tokenRe = /<g\s+id="([^"]+)"[^>]*>|<\/g>|<path\b([^>]*)\/?>/g;
let groupId = null;
let match;
while ((match = tokenRe.exec(svg)) !== null) {
  if (match[1]) { groupId = match[1]; continue; }
  if (match[0] === '</g>') { groupId = null; continue; }
  const attrs = match[2] || '';
  const d = (attrs.match(/\sd="([^"]+)"/) || [])[1];
  const ownId = (attrs.match(/\sid="([^"]+)"/) || [])[1];
  const id = groupId || ownId;
  if (!d || !id) continue;
  if (!countryPaths.has(id)) countryPaths.set(id, []);
  countryPaths.get(id).push(d);
}

const anchors = {};
for (const [id, ds] of countryPaths) {
  if (!/^[a-z]{2}$/.test(id)) continue; // skip non-ISO ids like "_somaliland"
  const polys = ds.flatMap(parsePolygons).map(polygonCentroid);
  const main = polys.reduce((best, p) => (p.area > best.area ? p : best), { area: -1 });
  anchors[id] = [Math.round(main.x * 10) / 10, Math.round(main.y * 10) / 10];
}

const body = Object.entries(anchors)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, [x, y]]) => `  ${id}: [${x}, ${y}]`)
  .join(',\n');

const output = `// AUTO-GENERATED by scripts/build-country-anchors.js from public/world-map.svg — do not edit.
// [x, y] = centroid of each country's main landmass in the SVG's coordinate space
// (viewBox "30.767 241.591 784.077 458.627").

export const MAP_VIEWBOX = { minX: 30.767, minY: 241.591, width: 784.077, height: 458.627 };

export const COUNTRY_ANCHORS = {
${body}
};
`;

fs.writeFileSync(OUT_PATH, output);
console.log(`Wrote ${Object.keys(anchors).length} country anchors to ${OUT_PATH}`);
console.log('Spot check:', ['us', 'gb', 'jp', 'au', 'br', 'in', 'kr', 'lk', 'ru', 'fr'].map(k => `${k}=${anchors[k]}`).join('  '));
